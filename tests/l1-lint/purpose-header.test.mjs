// L1 lint: every ts, tsx or sh source file added since the merge base with the PR target opens with a one-line purpose header (GH 1844).
import { strict as assert } from 'node:assert';
import { execFileSync } from 'node:child_process';
import { closeSync, mkdirSync, mkdtempSync, openSync, readSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { test } from 'node:test';
import { fileURLToPath } from 'node:url';

import { extractPurpose, PURPOSE_HEAD_BYTES } from '../../mcp/trajectory-server/dist/file-purpose.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const SCOPES = [/^src\//, /^mcp\/[^/]+\/src\//, /^dashboard\/src\//, /^scripts\//, /^skills\/[^/]+\/scripts\//];
const SOURCE_EXT = /\.(ts|tsx|sh)$/;
const HEADER_SOURCES = new Set(['comment', 'jsdoc', 'docstring']);
const GENERATED = /@generated|generated by/i;

function exemptPath(path) {
  return ['/test/', '.test.', '.spec.', 'fixtures/', 'dist/'].some((s) => path.includes(s)) || path.endsWith('.d.ts');
}

function readHead(file) {
  let fd;
  try {
    fd = openSync(file, 'r');
  } catch {
    return null;
  }
  try {
    const buf = Buffer.alloc(PURPOSE_HEAD_BYTES);
    const n = readSync(fd, buf, 0, PURPOSE_HEAD_BYTES, 0);
    return buf.subarray(0, n).toString('utf8');
  } finally {
    closeSync(fd);
  }
}

export function inScope(path) {
  return SOURCE_EXT.test(path) && SCOPES.some((re) => re.test(path)) && !exemptPath(path);
}

export function missingHeaders(root, paths) {
  const failing = [];
  for (const path of paths) {
    if (!inScope(path)) continue;
    const head = readHead(join(root, path));
    if (head === null || GENERATED.test(head)) continue;
    if (!HEADER_SOURCES.has(extractPurpose(path, head).source)) failing.push(path);
  }
  return failing;
}

function git(args) {
  return execFileSync('git', ['-C', ROOT, ...args], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
}

function resolveBase() {
  const candidates = process.env.TMB_LINT_BASE ? [process.env.TMB_LINT_BASE] : ['origin/dev', 'dev'];
  for (const ref of candidates) {
    try {
      return git(['merge-base', 'HEAD', ref]);
    } catch {}
  }
  return null;
}

function fixture(files) {
  const dir = mkdtempSync(join(tmpdir(), 'purpose-header-'));
  for (const [path, body] of Object.entries(files)) {
    mkdirSync(dirname(join(dir, path)), { recursive: true });
    writeFileSync(join(dir, path), body);
  }
  return dir;
}

test('a header-less source file fails until a one-line header is added', () => {
  const bare = {
    'src/x.ts': 'export const x = 1;\n',
    'dashboard/src/v.tsx': 'export const V = () => <div />;\n',
    'scripts/s.sh': '#!/usr/bin/env bash\nset -euo pipefail\necho hi\n',
  };
  const dir = fixture(bare);
  try {
    assert.deepEqual(missingHeaders(dir, Object.keys(bare)), Object.keys(bare));
    writeFileSync(join(dir, 'src/x.ts'), '// x does y.\nexport const x = 1;\n');
    writeFileSync(join(dir, 'dashboard/src/v.tsx'), '// v renders the view.\nexport const V = () => <div />;\n');
    writeFileSync(join(dir, 'scripts/s.sh'), '#!/usr/bin/env bash\n# s says hi.\nset -euo pipefail\necho hi\n');
    assert.deepEqual(missingHeaders(dir, Object.keys(bare)), []);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test('tests, fixtures, declarations and generated files are exempt; other types are ignored', () => {
  const body = 'export const a = 1;\n';
  const files = {
    'src/test/a.ts': body,
    'src/a.test.ts': body,
    'fixtures/b.ts': body,
    'scripts/fixtures/b.sh': 'echo\n',
    'src/c.d.ts': 'export declare const c: number;\n',
    'src/gen.ts': '/* eslint-disable */\n/** @generated */\nexport const g = 1;\n',
    'scripts/gen.sh': '#!/bin/sh\n# GENERATED BY make-gen\necho\n',
    'src/readme.md': 'no header\n',
    'src/data.json': '{}\n',
    'lib/outside.ts': body,
  };
  const dir = fixture(files);
  try {
    assert.deepEqual(missingHeaders(dir, Object.keys(files)), []);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test('every source file added on this branch has a purpose header', { timeout: 2000 }, (t) => {
  const started = performance.now();
  const base = resolveBase();
  if (!base) {
    t.skip('no base ref resolves (set TMB_LINT_BASE, or fetch origin/dev)');
    return;
  }
  const added = git(['diff', '--name-only', '--diff-filter=A', base]).split('\n').filter(Boolean);
  const failing = missingHeaders(ROOT, added);
  t.diagnostic(`checked ${added.length} added files in ${Math.round(performance.now() - started)} ms`);
  assert.deepEqual(failing, [], `open each with a one-line comment saying what the file is for:\n${failing.join('\n')}`);
});
