// Prune @primer/primitives to the tokens the dashboard uses and write
// web/theme/primer-tokens.css. Usage: node scripts/primer-tokens.mjs [out.css]
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const DASH = join(dirname(fileURLToPath(import.meta.url)), '..');
const PRIMITIVES = join(DASH, 'node_modules/@primer/primitives');
const OUT = process.argv[2] ?? join(DASH, 'web/theme/primer-tokens.css');

const SOURCES = [
  'base/size/size.css',
  'base/typography/typography.css',
  'functional/size/border.css',
  'functional/size/size.css',
  'functional/typography/typography.css',
  'functional/themes/light.css',
  'functional/themes/dark.css',
];

const PREFIXES = [
  '--bgColor-', '--fgColor-', '--borderColor-',
  '--button-default-', '--button-primary-', '--button-danger-', '--button-invisible-',
  '--control-', '--counter-', '--underlineNav-', '--header-', '--shadow-', '--focus-',
  '--overlay-', '--avatar-', '--borderWidth-', '--fontStack-', '--data-',
];

function parseBlocks(css) {
  const blocks = [];
  const stack = [];
  let buf = '';
  for (const ch of css.replace(/\/\*[\s\S]*?\*\//g, '')) {
    if (ch === '{') {
      stack.push({ prelude: buf.trim(), decls: [], children: [] });
      buf = '';
    } else if (ch === '}') {
      const block = stack.pop();
      (stack.at(-1)?.children ?? blocks).push(block);
      buf = '';
    } else if (ch === ';' && stack.length > 0) {
      const decl = /^(--[\w-]+)\s*:\s*([\s\S]+)$/.exec(buf.trim());
      if (decl) stack.at(-1).decls.push([decl[1], decl[2].trim()]);
      buf = '';
    } else {
      buf += ch;
    }
  }
  return blocks;
}

const files = SOURCES.map((f) => parseBlocks(readFileSync(join(PRIMITIVES, 'dist/css', f), 'utf8')));

const values = new Map();
const collect = (block) => {
  for (const [name, value] of block.decls) values.set(name, [...(values.get(name) ?? []), value]);
  block.children.forEach(collect);
};
files.flat().forEach(collect);

const keep = new Set([...values.keys()].filter((name) => PREFIXES.some((p) => name.startsWith(p))));
for (const pending = [...keep]; pending.length > 0; ) {
  for (const value of values.get(pending.pop()) ?? []) {
    for (const [, ref] of value.matchAll(/var\(\s*(--[\w-]+)/g)) {
      if (!keep.has(ref)) {
        keep.add(ref);
        pending.push(ref);
      }
    }
  }
}

const render = (block, indent) => {
  const inner = block.children.length > 0
    ? block.children.map((c) => render(c, `${indent}  `)).filter(Boolean)
    : block.decls.filter(([name]) => keep.has(name)).map(([name, value]) => `${indent}  ${name}: ${value};`);
  if (inner.length === 0) return '';
  const prelude = block.prelude.split(/,\s*/).join(`,\n${indent}`);
  return `${indent}${prelude} {\n${inner.join('\n')}\n${indent}}`;
};

const { version } = JSON.parse(readFileSync(join(PRIMITIVES, 'package.json'), 'utf8'));
const copyright = readFileSync(join(PRIMITIVES, 'LICENSE'), 'utf8').split('\n').find((l) => l.startsWith('Copyright'));
const header = [
  `/* Generated by scripts/primer-tokens.mjs from @primer/primitives ${version}; do not edit, run \`bun run tokens\`. */`,
  `/* @primer/primitives: ${copyright} Released under the MIT License. */`,
];
const body = files.flat().map((b) => render(b, '')).filter(Boolean);
writeFileSync(OUT, `${[...header, ...body].join('\n')}\n`);
